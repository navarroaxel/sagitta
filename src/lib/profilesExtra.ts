// Remaining double-T / channel series from the same CIRSOC 301-EL/302-EL "Tablas de Perfiles"
// (IRAM-IAS U 500-215-3/-4/-5 and U 500-509-2), same columns as profiles.ts.
// Kept apart from IPN/IPB on purpose: the 3D editor and stress check only use IPN/IPB (UPN is not
// symmetric about its weak axis, which the corner-stress check assumes), so getProfile() does not
// know these. Here the designation is NOT always the depth: IPBl 100 has h = 96 mm.
// Two Sx values (IPBl 1000, IPBv 320) are wrong in the source table itself and kept as printed.
// UPN below 80 (30x15 … 65) are left out: their rows are inconsistent in the scan.
import { build, type Geo, type Profile } from "./profiles";

type Row = Parameters<typeof build>[1][number];
// designation, then h, bf, tf, tw, A, Ix, Sx, rx, Iy, Sy, ry, J
type NamedRow = [string, ...Row];

function buildNamed(
  series: Profile["series"],
  rows: NamedRow[],
  geo: Geo[],
): Profile[] {
  return rows.map(([designation, ...row], i) => ({
    ...build(series, [row], [geo[i]])[0],
    name: `${series} ${designation}`,
  }));
}

const zip = (hw: number[], r: number[]): Geo[] => hw.map((v, i) => [v, r[i]]);

