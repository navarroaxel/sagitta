export type AnyTube = Tube | RectTube;
export type TubeKind = AnyTube["kind"];
export const ALL_TUBES: AnyTube[] = [...CHS_TUBES, ...SHS_TUBES, ...RHS_TUBES];

// ── search ──
export type TubeSortKey = string; // any numeric column of the kind being shown

export interface TubeQuery {
  text: string;
  kind: TubeKind;
  minI?: number; // I (circular/square) or Ix (rectangular)
  minS?: number; // S or Sx
  minA?: number;
  sortKey?: TubeSortKey;
  sortDir?: "asc" | "desc";
}

const num = (x: AnyTube, k: string) =>
  (x as unknown as Record<string, number>)[k];

// "168 6.35" finds CHS 168.3×6.35; "100 250" finds RHS 100×250×…; each number must prefix one of
// the outer dimensions or the thickness.
export function filterTubes(
  q: TubeQuery,
  all: AnyTube[] = ALL_TUBES,
): AnyTube[] {
  const nums =
    q.text.match(/\d+(?:[.,]\d+)?/g)?.map((n) => n.replace(",", ".")) ?? [];
  const dims = (x: AnyTube) =>
    (x.kind === "RHS" ? [x.B, x.H, x.t] : [x.D, x.t]).map(String);
  const out = all.filter((x) => {
    if (x.kind !== q.kind) return false;
    const d = dims(x);
    if (!nums.every((n) => d.some((v) => v.startsWith(n)))) return false;
    const rect = x.kind === "RHS";
    if (q.minI !== undefined && num(x, rect ? "Ix" : "I") < q.minI)
      return false;
    if (q.minS !== undefined && num(x, rect ? "Sx" : "S") < q.minS)
      return false;
    if (q.minA !== undefined && x.A < q.minA) return false;
    return true;
  });
  if (q.sortKey) {
    const k = q.sortKey;
    const dir = q.sortDir === "desc" ? -1 : 1;
    out.sort((a, b) => (num(a, k) - num(b, k)) * dir);
  }
  return out;
}
