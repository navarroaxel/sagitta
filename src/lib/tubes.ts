// ── search ──
export type TubeSortKey = Exclude<keyof Tube, "name" | "kind">;

export interface TubeQuery {
  text: string;
  kind: Tube["kind"];
  minI?: number;
  minS?: number;
  minA?: number;
  sortKey?: TubeSortKey;
  sortDir?: "asc" | "desc";
}

// "168 6.35" finds Ø168.3×6.35; "100" finds every 100 mm tube; numbers must each prefix the
// outer dimension or the thickness.
export function filterTubes(q: TubeQuery, all: Tube[] = ALL_TUBES): Tube[] {
  const nums =
    q.text.match(/\d+(?:[.,]\d+)?/g)?.map((n) => n.replace(",", ".")) ?? [];
  const out = all.filter((x) => {
    if (x.kind !== q.kind) return false;
    if (
      !nums.every((n) => String(x.D).startsWith(n) || String(x.t).startsWith(n))
    )
      return false;
    if (q.minI !== undefined && x.I < q.minI) return false;
    if (q.minS !== undefined && x.S < q.minS) return false;
    if (q.minA !== undefined && x.A < q.minA) return false;
    return true;
  });
  if (q.sortKey) {
    const k = q.sortKey;
    const dir = q.sortDir === "desc" ? -1 : 1;
    out.sort((a, b) => (a[k] - b[k]) * dir);
  }
  return out;
}
