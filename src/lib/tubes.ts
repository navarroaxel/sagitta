// Torsional modulus C = 2·A_h·t, A_h = area enclosed by the mid-line (corner radius 1.5t).
export const torsionC = (B: number, H: number, t: number) =>
  (2 * ((B - t) * (H - t) - (1.5 * t) ** 2 * (4 - Math.PI)) * t) / 1e3;

