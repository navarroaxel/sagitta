export function circularTube(D: number, t: number): Tube {
  const d = D - 2 * t;
  const A = ((Math.PI / 4) * (D * D - d * d)) / 100;
  const I = ((Math.PI / 64) * (D ** 4 - d ** 4)) / 1e4;
  const S = I / (D / 20);
  return {
    name: `CHS ${D}×${t}`,
    kind: "CHS",
    D,
    t,
    A: r2(A),
    g: r2(A * STEEL),
    I: r2(I),
    S: r2(S),
    r: r2(Math.sqrt(I / A)),
    Z: r2((D ** 3 - d ** 3) / 6 / 1e3),
    J: r2(2 * I),
    C: r2(((Math.PI / 2) * (D - t) ** 2 * t) / 1e3),
  };
}

